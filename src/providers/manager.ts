import fs from "node:fs";
import path from "node:path";
import { analyzeProject } from "../analyzer/project-analyzer.js";
import { listInstalled } from "../packs/installer.js";
import { listSyntra } from "../syntra/manager.js";
import { getLatestHandoff } from "../handoff/manager.js";
import { getProvider, providers } from "./adapters.js";
import { loadCommands } from "../commands/registry.js";
import { resolveInstructions } from "../instructions/resolver.js";
import { resolveAgents } from "../agents/resolver.js";
import { resolveSkills, resolveSkillsForAgent } from "../skills/resolver.js";
import type { ProviderArtifact, ProviderContext, ProviderId, ProviderCommandProjection } from "./types.js";
import { locateOrchestraX } from "../workspace/discovery.js";

export interface ProviderSyncResult {
  provider: ProviderId;
  artifacts: string[];
  skipped: string[];
}

function buildContext(project: { id: string; name: string; path: string }, workspaceRoot: string, orchestraxRoot: string): ProviderContext {
  const profile = analyzeProject(project);
  const syntra = listSyntra(project.path);
  const handoff = getLatestHandoff(project.path);
  const instructionResolution = resolveInstructions(orchestraxRoot, workspaceRoot, project);
  const agentResolution = resolveAgents(orchestraxRoot, workspaceRoot, project);
  const skillResolution = resolveSkills(orchestraxRoot, workspaceRoot, project);
  const skillMap = new Map(skillResolution.skills.map(s => [s.id.toLowerCase(), s]));
  for (const agent of agentResolution.agents) for (const skill of resolveSkillsForAgent(orchestraxRoot, workspaceRoot, project, agent.id).skills) skillMap.set(skill.id.toLowerCase(), skill);
  const effectiveSkills = [...skillMap.values()];
  return {
    projectProfile: { signals: profile.signals },
    installedPacks: listInstalled(project.path),
    skills: effectiveSkills.map(s => ({ id: s.id, version: s.version, category: s.category, source: s.source, capabilities: s.capabilities, appliesToAgents: s.appliesToAgents, content: s.content })),
    instructions: instructionResolution.instructions.map(i => ({ id: i.id, version: i.version, category: i.category, source: i.source, required: i.required, content: i.content })),
    agents: agentResolution.agents.map(a => ({ id: a.id, version: a.version, role: a.role, source: a.source, capabilities: a.capabilities, content: a.content, requiredInstructions: a.resolvedInstructions, resolvedSkills: a.resolvedSkills })),
    syntra: syntra.map(e => ({ title: e.title, content: e.content, category: e.category, status: e.status })),
    latestHandoff: handoff ? { title: handoff.title, objective: handoff.objective, nextAction: handoff.nextAction } : undefined
  };
}

function isManaged(content: string): boolean {
  return content.includes("Generated by Neo OrchestraX. Do not edit this file directly; use provider sync.");
}

function writeArtifact(projectPath: string, artifact: ProviderArtifact): "written" | "skipped" {
  const target = path.join(projectPath, artifact.relativePath);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  if (fs.existsSync(target) && !isManaged(fs.readFileSync(target, "utf8"))) return "skipped";
  fs.writeFileSync(target, artifact.content + "\n", "utf8");
  return "written";
}

export function syncProvider(project: { id: string; name: string; path: string }, providerId: string): ProviderSyncResult {
  const provider = getProvider(providerId);
  if (!provider) throw new Error(`Unknown provider: ${providerId}`);
  const located = locateOrchestraX(project.path);
  const workspaceRoot = located.workspaceRoot;
  const orchestraxRoot = located.orchestraxRoot;
  const context = buildContext(project, workspaceRoot, orchestraxRoot);
  const result: ProviderSyncResult = { provider: provider.id, artifacts: [], skipped: [] };
  for (const artifact of provider.generate(project, context)) {
    (writeArtifact(project.path, artifact) === "written" ? result.artifacts : result.skipped).push(artifact.relativePath);
  }
  writeManifest(project.path, path.join(orchestraxRoot, "commands"));
  return result;
}

export function syncAllProviders(project: { id: string; name: string; path: string }): ProviderSyncResult[] {
  return providers.map(p => syncProvider(project, p.id));
}

export function listProviders() {
  return providers.map(p => ({ id: p.id, name: p.name, description: p.description, capabilities: p.capabilities }));
}

export function projectProviderCommands(projectPath: string, providerId: string): ProviderCommandProjection[] {
  const provider = getProvider(providerId);
  if (!provider) throw new Error(`Unknown provider: ${providerId}`);
  const orchestraxRoot = locateOrchestraX(projectPath).orchestraxRoot;
  const commands = loadCommands(path.join(orchestraxRoot, "commands"));
  return provider.projectCommands(commands);
}

function writeManifest(projectPath: string, commandsRoot: string): void {
  const dir = path.join(projectPath, ".orchestrax", "providers");
  fs.mkdirSync(dir, { recursive: true });
  const commands = loadCommands(commandsRoot);
  fs.writeFileSync(path.join(dir, "manifest.json"), JSON.stringify({
    generatedBy: "neo-orchestrax",
    version: "0.14.7",
    providers: providers.map(p => ({ id: p.id, capabilities: p.capabilities })),
    aiCommands: commands.map(command => ({ id: command.id, version: command.version, description: command.description, usage: command.usage })),
    updatedAt: new Date().toISOString()
  }, null, 2) + "\n", "utf8");
}

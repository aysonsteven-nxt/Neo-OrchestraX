import type { ProviderAdapter, ProviderArtifact, ProviderContext } from "./types.js";

const header = "<!-- Generated by Neo OrchestraX. Do not edit this file directly; use provider sync. -->";

function canonical(project: { name: string }, context: ProviderContext): string {
  const signals = context.projectProfile.signals.map(s => `- ${s.value} (${s.category}): ${s.evidence}`);
  const syntra = context.syntra
    .filter(e => ["confirmed", "review"].includes(e.status))
    .slice(0, 20)
    .map(e => `- **${e.title}** [${e.category}/${e.status}]: ${e.content}`);
  const instructions = context.instructions
    .map(i => `### ${i.id} @ ${i.version} (${i.source}${i.required ? ", required" : ""})\n${i.content}`)
    .join("\n\n");
  const instructionSection = instructions
    ? `\n## Effective OrchestraX Rails / Instructions\n${instructions}\n`
    : "";
  const skills = context.skills
    .map(s => `### ${s.id} @ ${s.version} (${s.source}/${s.category})\n${s.content}\n\nCapabilities: ${s.capabilities.join(", ") || "none"}\nMapped agents: ${s.appliesToAgents.join(", ") || "all"}`)
    .join("\n\n");
  const skillSection = skills
    ? `\n## Effective OrchestraX Skills\n${skills}\n`
    : "";
  const agents = context.agents.map(a => `### ${a.id} @ ${a.version} (${a.role})\n${a.content}\n\nCapabilities: ${a.capabilities.join(", ") || "none"}\n\nInstruction dependencies:\n${a.requiredInstructions.map(d => `- ${d.id} @ ${d.version} (${d.required ? "required" : "optional"}${d.available ? ", available" : ", missing"})`).join("\n")}\n\nSkill dependencies:\n${a.resolvedSkills.map(d => `- ${d.id} @ ${d.version} (${d.required ? "required" : "optional"}${d.available ? ", available" : ", missing"})`).join("\n")}`).join("\n\n");
  const agentSection = agents ? `\n## Applicable OrchestraX Agents\n${agents}\n` : "";

  const handoff = context.latestHandoff
    ? `\n## Current continuity\n- Handoff: ${context.latestHandoff.title}\n- Objective: ${context.latestHandoff.objective}${context.latestHandoff.nextAction ? `\n- Next action: ${context.latestHandoff.nextAction}` : ""}\n`
    : "";

  return `${header}\n# Neo OrchestraX — ${project.name}\n\nUse Neo OrchestraX project context when working on this project. Prefer confirmed project knowledge and current task/handoff state over assumptions. Do not treat inferred or draft information as authoritative.\n\n## Technology signals\n${signals.length ? signals.join("\n") : "- No project signals detected."}\n${instructionSection}${skillSection}${agentSection}\n## Installed OrchestraX packs\n${context.installedPacks.length ? context.installedPacks.map(p => `- ${p}`).join("\n") : "- None detected."}\n\n## Relevant Syntra knowledge\n${syntra.length ? syntra.join("\n") : "- No confirmed/review knowledge available."}\n${handoff}`;
}

function adapter(id: "copilot" | "gemini" | "claude" | "cursor", name: string, description: string, paths: (ctx: string) => ProviderArtifact[]): ProviderAdapter {
  return { id, name, description, generate: (project, context) => paths(canonical(project, context)) };
}

export const providers: ProviderAdapter[] = [
  adapter("copilot", "GitHub Copilot", "GitHub Copilot repository instructions and agent context.", ctx => [
    { relativePath: ".github/copilot-instructions.md", content: ctx },
    { relativePath: ".github/agents/orchestrax-context.agent.md", content: `${header}\n---\ndescription: Neo OrchestraX project context\n---\n\n${ctx}` }
  ]),
  adapter("gemini", "Gemini / Antigravity", "Gemini project guidance and shared project context.", ctx => [
    { relativePath: "GEMINI.md", content: ctx }
  ]),
  adapter("claude", "Claude Code", "Claude Code project instructions and agent context.", ctx => [
    { relativePath: ".claude/CLAUDE.md", content: ctx },
    { relativePath: ".claude/agents/orchestrax-context.md", content: `${header}\n\n${ctx}` }
  ]),
  adapter("cursor", "Cursor", "Cursor project rules and shared project context.", ctx => [
    { relativePath: ".cursor/rules/orchestrax-context.mdc", content: `${header}\ndescription: Neo OrchestraX project context\nalwaysApply: true\n\n${ctx}` }
  ])
];

export function getProvider(id: string): ProviderAdapter | undefined {
  return providers.find(p => p.id === id.toLowerCase());
}

import os from "node:os";
import path from "node:path";
import type { OrchestraCommandDefinition } from "../commands/registry.js";

export const copilotUserSkillsRoot = (): string => path.join(os.homedir(), ".copilot", "skills");

const header = "<!-- Generated by Neo OrchestraX. Do not edit this file directly; use provider sync. -->";

const cliMap: Record<string, string> = {
  "package-selector": "npm --prefix neo-orchestrax start -- pack recommend <project>",
  "package-install": "npm --prefix neo-orchestrax start -- pack install <pack> <project>",
  "package-list": "npm --prefix neo-orchestrax start -- pack list",
  "package-installed": "npm --prefix neo-orchestrax start -- pack installed <project>",
  "package-remove": "npm --prefix neo-orchestrax start -- pack remove <pack> <project>",
  "package-validate": "npm --prefix neo-orchestrax start -- pack validate <pack>",
  "context": "npm --prefix neo-orchestrax start -- context <project> [query]",
  "task": "npm --prefix neo-orchestrax start -- task <start|list|show|status|context> <project> ...",
  "handoff": "npm --prefix neo-orchestrax start -- handoff <create|list|show|latest> <project> ...",
  "resume": "npm --prefix neo-orchestrax start -- resume <project> [handoff-id]",
  "instructions": "npm --prefix neo-orchestrax start -- instruction <list|show|effective> <project> ...",
  "agents": "npm --prefix neo-orchestrax start -- agent <list|show|effective> <project> ...",
  "agent": "npm --prefix neo-orchestrax start -- agent show <project> <agent-id>",
  "skills": "npm --prefix neo-orchestrax start -- skill <list|show|effective> <project> ...",
  "skill": "npm --prefix neo-orchestrax start -- skill show <project> <skill-id>",
  "provider-sync": "npm --prefix neo-orchestrax start -- provider sync <project> [provider]",
  "pack": "npm --prefix neo-orchestrax start -- pack <list|show|graph|validate|compose> ..."
};

export interface CopilotSkillArtifact {
  skillName: string;
  content: string;
}

const reservedCopilotSlashCommands = new Set([
  "skills",
  "help",
  "plan",
  "explain",
  "fix",
  "tests",
  "doc",
  "new",
  "newNotebook",
  "compact",
  "fork",
  "clear",
  "rename"
]);

function copilotSkillName(commandName: string): string {
  return reservedCopilotSlashCommands.has(commandName) ? `orchestrax-${commandName}` : commandName;
}

export function buildCopilotSkill(command: OrchestraCommandDefinition): CopilotSkillArtifact {
  const cli = cliMap[command.name] ?? `npm --prefix neo-orchestrax start -- ${command.name} ...`;
  const skillName = copilotSkillName(command.name);
  const argumentHint = command.argumentHint ? `\nargument-hint: "${command.argumentHint.replace(/"/g, "\\\"")}"` : "";

  const content = `${header}
---
name: ${skillName}
description: ${command.description}${argumentHint}
user-invocable: true
disable-model-invocation: true
---

You are invoking the Neo OrchestraX action \`/${skillName}\` (canonical action: \`/${command.name}\`).

Use the user's text after the slash command as the action arguments. Resolve the target project using OrchestraX's normal targeting rules. Do not invent project names, pack names, agent IDs, skill IDs, or instruction IDs.

Use the Neo OrchestraX CLI as the source of truth. From the workspace root, run:

\`${cli}\`

Interpret the CLI result and present it to the user. For actions that mutate state, perform the requested operation through the CLI rather than editing OrchestraX state files directly.
`;

  return { skillName, content };
}
